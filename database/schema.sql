CREATE TABLE IF NOT EXISTS farmers (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(120) NOT NULL, location VARCHAR(160) NOT NULL,
 phone VARCHAR(40), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS suppliers (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(120) NOT NULL, location VARCHAR(160) NOT NULL,
 farmer_id BIGINT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_supplier_farmer FOREIGN KEY (farmer_id) REFERENCES farmers(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS products (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, sku VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(140) NOT NULL,
 category VARCHAR(80) NOT NULL, description TEXT, unit VARCHAR(30) NOT NULL DEFAULT 'kg',
 price DECIMAL(12,2) NOT NULL DEFAULT 0, demand INT NOT NULL DEFAULT 0,
 supplier_id BIGINT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY ix_products_name (name),
 CONSTRAINT fk_product_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS warehouses (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(120) NOT NULL, location VARCHAR(160) NOT NULL,
 capacity INT NOT NULL, CHECK (capacity >= 0)
);
CREATE TABLE IF NOT EXISTS inventory (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, product_id BIGINT NOT NULL, warehouse_id BIGINT NOT NULL,
 quantity INT NOT NULL DEFAULT 0, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT uq_inventory_product_warehouse UNIQUE(product_id, warehouse_id),
 CONSTRAINT fk_inventory_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
 CONSTRAINT fk_inventory_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouses(id) ON DELETE CASCADE,
 CHECK (quantity >= 0)
);
CREATE TABLE IF NOT EXISTS customer_orders (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, customer_name VARCHAR(140) NOT NULL, destination VARCHAR(180) NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'PLACED', total_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, product_id BIGINT NOT NULL,
 quantity INT NOT NULL, unit_price DECIMAL(12,2) NOT NULL,
 CONSTRAINT fk_item_order FOREIGN KEY (order_id) REFERENCES customer_orders(id) ON DELETE CASCADE,
 CONSTRAINT fk_item_product FOREIGN KEY (product_id) REFERENCES products(id), CHECK (quantity > 0)
);
CREATE TABLE IF NOT EXISTS shipments (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL UNIQUE, tracking_code VARCHAR(70) NOT NULL UNIQUE,
 warehouse_id BIGINT NULL, destination VARCHAR(180) NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'READY',
 shipped_at TIMESTAMP NULL, CONSTRAINT fk_shipment_order FOREIGN KEY (order_id) REFERENCES customer_orders(id) ON DELETE CASCADE,
 CONSTRAINT fk_shipment_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouses(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS quality_reports (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, product_id BIGINT NOT NULL, supplier_id BIGINT NULL,
 severity VARCHAR(24) NOT NULL DEFAULT 'INFO', details TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_report_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
 CONSTRAINT fk_report_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS distribution_edges (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, from_node VARCHAR(120) NOT NULL, to_node VARCHAR(120) NOT NULL,
 capacity INT NOT NULL, CHECK (capacity >= 0)
);
